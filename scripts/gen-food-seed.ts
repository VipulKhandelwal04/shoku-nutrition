// Generates the food catalogue seed migration from src/lib/seed-foods.ts.
// Run: node scripts/gen-food-seed.ts  (Node 24 strips TypeScript types natively)
import { writeFileSync } from 'node:fs';
import { SEED_FOODS } from '../src/lib/seed-foods.ts';

const q = (s: string) => `'${s.replaceAll("'", "''")}'`;
const values = SEED_FOODS.map(f =>
  `  (${[q(f.id), q(f.name), q(f.category), q(f.unit), f.grams, f.kcal, f.p, f.c, f.f, f.fibre, q(f.diet), q(f.icon), q(f.aliases), `${q(JSON.stringify(f.groups))}::jsonb`].join(', ')})`,
).join(',\n');

const sql = `-- Generated by scripts/gen-food-seed.ts. Starter catalogue; admins edit the live rows.
insert into public.foods (id, name, category, unit, grams, kcal, p, c, f, fibre, diet, icon, aliases, groups) values
${values}
on conflict (id) do nothing;
`;
writeFileSync(new URL('../supabase/migrations/20261015000002_seed_foods.sql', import.meta.url), sql);
console.log(`Wrote ${SEED_FOODS.length} foods`);
