// Generates the first-recipes seed migration from src/lib/seed-recipes.ts.
// Run: node scripts/gen-recipe-seed.ts  (Node 24 strips TypeScript types natively)
import { writeFileSync } from 'node:fs';
import { SEED_RECIPES } from '../src/lib/seed-recipes.ts';

const q = (s: string) => `'${s.replaceAll("'", "''")}'`;
const arr = (list: string[]) => `array[${list.map(q).join(', ')}]::text[]`;
const values = SEED_RECIPES.map(r =>
  `  (${[q(r.name), q(r.cuisine), r.servings, arr(r.steps), `${q(JSON.stringify(r.ingredients))}::jsonb`].join(', ')})`,
).join(',\n');

const sql = `-- Generated by scripts/gen-recipe-seed.ts. First recipes (#14), built only from catalogue foods.
-- Active from the start; admins edit or hide them in Admin → Recipes. Skips any recipe whose name already exists,
-- and any whose ingredients are no longer all in the catalogue.
insert into public.recipes (name, cuisine, servings, steps, ingredients, active)
select v.name, v.cuisine, v.servings, v.steps, v.ingredients, true
from (values
${values}
) as v(name, cuisine, servings, steps, ingredients)
where not exists (select 1 from public.recipes r where lower(r.name) = lower(v.name))
  and not exists (
    select 1 from jsonb_array_elements(v.ingredients) e
    where not exists (select 1 from public.foods f where f.id = e ->> 'foodId' and f.owner_id is null)
  );
`;
writeFileSync(new URL('../supabase/migrations/20261015000016_first_recipes.sql', import.meta.url), sql);
console.log(`Wrote ${SEED_RECIPES.length} recipes`);
